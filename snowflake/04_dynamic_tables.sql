-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT supply_base.ID AS ENTITY_ID, supply_base.NAME AS ENTITY_NAME,
       supply_base.REGION, supply_base.CATEGORY, supply_base.RISK_TIER, supply_base.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.DELIVERY_COUNT) AS DELIVERY_COUNT,
       SUM(observation.TRACED_TONNES) AS TRACED_TONNES,
       SUM(observation.FFB_TONNES) AS FFB_TONNES,
       SUM(observation.FLAG_COUNT) AS FLAG_COUNT,
       SUM(observation.CONFIRMED_COUNT) AS CONFIRMED_COUNT,
       SUM(observation.LOTS_EXCLUDED) AS EXCLUDED_COUNT,
       SUM(observation.DECLARATION_DUE) AS DECLARATION_DUE,
       SUM(observation.DECLARATION_RECEIVED) AS DECLARATION_RECEIVED,
       100.0 * SUM(observation.TRACED_TONNES) / NULLIF(SUM(observation.FFB_TONNES), 0) AS TRACEABILITY_PCT,
       100.0 * SUM(observation.CONFIRMED_COUNT) / NULLIF(SUM(observation.FLAG_COUNT), 0) AS FLAG_PRECISION_PCT,
       100.0 * SUM(observation.DECLARATION_RECEIVED) / NULLIF(SUM(observation.DECLARATION_DUE), 0) AS DECLARATION_PCT,
       AVG(observation.GEO_MISMATCH_PCT) AS AVG_GEO_MISMATCH_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.SUPPLY_DAILY observation
JOIN RAW.SUPPLY_BASES supply_base ON supply_base.ID = observation.ENTITY_ID
GROUP BY supply_base.ID, supply_base.NAME, supply_base.REGION, supply_base.CATEGORY, supply_base.RISK_TIER, supply_base.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(DELIVERY_COUNT) AS DELIVERY_COUNT, SUM(TRACED_TONNES) AS TRACED_TONNES,
       SUM(FFB_TONNES) AS FFB_TONNES,
       SUM(FLAG_COUNT) AS FLAG_COUNT, SUM(CONFIRMED_COUNT) AS CONFIRMED_COUNT,
       100.0 * SUM(TRACED_TONNES) / NULLIF(SUM(FFB_TONNES), 0) AS TRACEABILITY_PCT
FROM RAW.SUPPLY_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.SIGNAL_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT RISK_SIGNAL, SUM(FLAG_COUNT) AS FLAG_COUNT,
       SUM(CONFIRMED_COUNT) AS CONFIRMED_COUNT,
       SUM(LOTS_EXCLUDED) AS EXCLUDED_COUNT,
       SUM(TRACED_TONNES) AS FLAGGED_DAY_TRACED_TONNES,
       100.0 * SUM(CONFIRMED_COUNT) / NULLIF(SUM(FLAG_COUNT), 0) AS FLAG_PRECISION_PCT
FROM RAW.SUPPLY_DAILY
WHERE FLAG_COUNT > 0
GROUP BY RISK_SIGNAL;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(DELIVERY_COUNT) AS DELIVERIES, SUM(TRACED_TONNES) AS TRACED,
         SUM(FFB_TONNES) AS INTAKE,
         SUM(FLAG_COUNT) AS FLAGS, SUM(CONFIRMED_COUNT) AS CONFIRMED,
         SUM(LOTS_EXCLUDED) AS EXCLUDED,
         SUM(DECLARATION_DUE) AS DECLARATION_DUE, SUM(DECLARATION_RECEIVED) AS DECLARATION_RECEIVED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.SUPPLY_DAILY
), portfolio AS (SELECT COUNT(*) AS BASE_COUNT FROM RAW.SUPPLY_BASES),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING, SUM(REQUIRED_QTY) AS REGISTERED
  FROM RAW.PLOT_REGISTRY
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Traceability to Plot' AS TITLE,
         100.0 * TRACED / NULLIF(INTAKE, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'FFB Deliveries', DELIVERIES, '' FROM observations
  UNION ALL SELECT 3, 'FFB Intake (kt)', INTAKE / 1e3, '' FROM observations
  UNION ALL SELECT 4, 'Screening Flags', FLAGS, '' FROM observations
  UNION ALL SELECT 5, 'Confirmed Canopy-Loss Cases', CONFIRMED, '' FROM observations
  UNION ALL SELECT 6, 'Flag Precision', 100.0 * CONFIRMED / NULLIF(FLAGS, 0), '%' FROM observations
  UNION ALL SELECT 7, 'Lots Excluded from EU Stock', EXCLUDED, '' FROM observations
  UNION ALL SELECT 8, 'Supplier Declaration Rate', 100.0 * DECLARATION_RECEIVED / NULLIF(DECLARATION_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Supply Bases Monitored', BASE_COUNT, '' FROM portfolio
  UNION ALL SELECT 10, 'Plot Geolocation Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Geolocation Checks Pending', PENDING, '' FROM documents
  UNION ALL SELECT 12, 'Registered Plots', REGISTERED, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.SIGNAL_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;

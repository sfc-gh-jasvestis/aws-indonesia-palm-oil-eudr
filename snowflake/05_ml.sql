-- Canopy-loss risk scoring and FFB delivery forecast over the synthetic snapshot.
-- Predicts P(confirmed canopy-loss case in the next 7 days) per supply base and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.CANOPY_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, b.CATEGORY, b.RISK_TIER, b.PROGRAM_YEARS,
       r.GEO_MISMATCH_PCT, r.UNMAPPED_PCT,
       AVG(r.GEO_MISMATCH_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS GEO_MISMATCH_7D,
       SUM(r.CONFIRMED_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS CONFIRMED_30D,
       IFF(SUM(r.CONFIRMED_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'LOSS', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.SUPPLY_DAILY r JOIN RAW.SUPPLY_BASES b ON b.ID = r.ENTITY_ID
-- Fire hotspot clusters are area-wide, not base-driven, so they are excluded from training.
WHERE r.RISK_SIGNAL <> 'Fire hotspot cluster';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.CANOPY_TRAIN AS
SELECT CATEGORY, RISK_TIER, PROGRAM_YEARS, GEO_MISMATCH_PCT, UNMAPPED_PCT, GEO_MISMATCH_7D, CONFIRMED_30D, LABEL
FROM ML.CANOPY_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.CANOPY_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, PROGRAM_YEARS, GEO_MISMATCH_PCT, UNMAPPED_PCT, GEO_MISMATCH_7D, CONFIRMED_30D, LABEL
FROM ML.CANOPY_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.CANOPY_RISK_MODEL(
  INPUT_DATA => TABLE(ML.CANOPY_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.CANOPY_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.CANOPY_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'PROGRAM_YEARS', PROGRAM_YEARS,
           'GEO_MISMATCH_PCT', GEO_MISMATCH_PCT, 'UNMAPPED_PCT', UNMAPPED_PCT,
           'GEO_MISMATCH_7D', GEO_MISMATCH_7D, 'CONFIRMED_30D', CONFIRMED_30D)):probability:LOSS::FLOAT AS P
  FROM ML.CANOPY_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'LOSS', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'LOSS', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'LOSS', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'LOSS', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per supply base (label unknown, so excluded from features).
CREATE TABLE ML.CANOPY_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.CANOPY_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.CANOPY_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'PROGRAM_YEARS', PROGRAM_YEARS,
           'GEO_MISMATCH_PCT', GEO_MISMATCH_PCT, 'UNMAPPED_PCT', UNMAPPED_PCT,
           'GEO_MISMATCH_7D', GEO_MISMATCH_7D, 'CONFIRMED_30D', CONFIRMED_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:LOSS::FLOAT, 4) AS LOSS_PROB_7D,
       CASE WHEN P:probability:LOSS::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:LOSS::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide daily FFB delivery forecast (14 days), for mill intake planning.
CREATE VIEW ML.DAILY_DELIVERIES AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(DELIVERY_COUNT)::FLOAT AS DELIVERY_COUNT
FROM RAW.SUPPLY_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.DELIVERY_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_DELIVERIES),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'DELIVERY_COUNT'
);

CREATE TABLE ML.DELIVERY_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS DELIVERY_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.DELIVERY_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
